from __future__ import annotations

from typing import Any, Optional, Protocol


class DataRepository(Protocol):
    """컬렉션 `data`: {date: 'YYYY-MM-DD', value: float, memo: str, created_at, updated_at}"""

    def list_all(self) -> list[dict[str, Any]]: ...
    def get(self, item_id: str) -> Optional[dict[str, Any]]: ...
    def find_by_date(self, date: str) -> Optional[dict[str, Any]]: ...
    def create(self, data: dict[str, Any]) -> str: ...
    def update(self, item_id: str, fields: dict[str, Any]) -> None: ...
    def delete(self, item_id: str) -> None: ...
    def bulk_create(self, rows: list[dict[str, Any]]) -> int: ...
    def delete_all(self) -> int: ...


class ConversationRepository(Protocol):
    """컬렉션 `conversations`:
    {title, messages: [{role, content, timestamp, tool_calls}], message_count, last_message, created_at, updated_at}
    """

    def list(self, limit: int) -> list[dict[str, Any]]: ...          # messages 제외
    def get(self, conv_id: str) -> Optional[dict[str, Any]]: ...      # messages 포함
    def create(self, data: dict[str, Any]) -> str: ...
    def update(self, conv_id: str, fields: dict[str, Any]) -> None: ...
    def delete(self, conv_id: str) -> None: ...
